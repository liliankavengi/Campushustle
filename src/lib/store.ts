  resolveMpesaCallback(checkoutRequestId: string, success: boolean, receiptNumber?: string) {
    const receipt = receiptNumber || `SLK${Math.floor(10000000 + Math.random() * 90000000)}KE`;
    
    this.transactions = this.transactions.map((tx) => {
      if (tx.checkoutRequestId === checkoutRequestId) {
        return {
          ...tx,
          status: success ? 'SUCCESS' : 'FAILED',
          resultCode: success ? 0 : 1032,
          resultDesc: success ? 'The service request is processed successfully.' : 'Request cancelled by user.',
          mpesaReceipt: success ? receipt : undefined,
        };
      }
      return tx;
    });

    if (success) {
      const tx = this.transactions.find((t) => t.checkoutRequestId === checkoutRequestId);
      if (tx && tx.purpose === 'SUBSCRIPTION_PASS') {
        const expires = new Date();
        expires.setDate(expires.getDate() + 120);
        this.subscription = {
          id: `sub-${Date.now()}`,
          userId: this.user.id,
          amount: tx.amount,
          mpesaReceipt: receipt,
          status: 'ACTIVE',
          serviceType: 'SEMESTER_ALL_ACCESS',
          expiresAt: expires.toISOString(),
          createdAt: new Date().toISOString(),
        };

        this.services = this.services.map((srv) => {
          if (srv.serviceId === 'srv-all-access') {
            return {
              ...srv,
              subscriberCount: srv.subscriberCount + 1,
              revenueKes: srv.revenueKes + tx.amount,
            };
          }
          return srv;
        });
      }
    }

    this.notify();
  }

