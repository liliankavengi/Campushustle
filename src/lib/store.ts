// Global hook
export function useCampusStore() {
  const store = CampusHustleStore.getInstance();
  const [, setTick] = useState(0);

  useEffect(() => {
    return store.subscribe(() => setTick((t) => t + 1));
  }, [store]);

  return store;
}

// Timestamp formatting helper
export function formatLaunchTime(isoString: string): { relative: string; exact: string; timeOnly: string } {
  try {
    const date = new Date(isoString);
    const now = new Date();
    const diffSeconds = Math.max(0, Math.floor((now.getTime() - date.getTime()) / 1000));

    let relative = 'Just now';
    if (diffSeconds < 45) {
      relative = 'Just now';
    } else if (diffSeconds < 90) {
      relative = '1 min ago';
    } else if (diffSeconds < 3600) {
      relative = `${Math.floor(diffSeconds / 60)} mins ago`;
    } else if (diffSeconds < 86400) {
      const hours = Math.floor(diffSeconds / 3600);
      relative = hours === 1 ? '1 hour ago' : `${hours} hours ago`;
    } else {
      const days = Math.floor(diffSeconds / 86400);
      relative = days === 1 ? 'Yesterday' : `${days} days ago`;
    }

    const timeOnly = date.toLocaleTimeString([], { hour: '2-digit', minute: '2-digit', second: '2-digit' });
    const exact = `${date.toLocaleDateString([], { month: 'short', day: 'numeric' })} at ${timeOnly}`;

    return { relative, exact, timeOnly };
  } catch (e) {
    return { relative: 'Recently', exact: isoString, timeOnly: '' };
  }
}
